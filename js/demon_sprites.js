// 便利関数：キー → canvas（整数倍・最近傍）
Object.defineProperty(window.DEMON_SPRITES, '__toCanvas', {
  enumerable: false,
  value(key, scale = 1) {
    const s = window.DEMON_SPRITES[key];
    if (!s) return null;
    scale = Math.max(1, scale | 0);
    const w = s.rows[0].length, h = s.rows.length;
    const c = document.createElement('canvas');
    c.width = w * scale; c.height = h * scale;
    const x = c.getContext('2d');
    for (let y = 0; y < h; y++) {
      const row = s.rows[y];
      for (let i = 0; i < w; i++) {
        const col = s.pal[row[i]];
        if (!col) continue;
        x.fillStyle = col; x.fillRect(i * scale, y * scale, scale, scale);
      }
    }
    return c;
  },
});
